-- Se generó (fuera de este script, con Python/openpyxl) un mapeo DNI → SIGLA
-- de Dependencia leyendo las 663 filas con dato de esa columna, normalizando
-- tildes/mojibake y deduplicando 77 variantes de texto contra las 45
