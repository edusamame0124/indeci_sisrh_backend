    v_persona_id     NUMBER;
    v_empleado_id    NUMBER;
    v_dependencia_id NUMBER;
    v_actualizados   NUMBER;

    v_ok         NUMBER := 0;
    v_sin_dni    NUMBER := 0;
    v_sin_cambio NUMBER := 0;
BEGIN
    IF v_dnis.COUNT != v_siglas.COUNT THEN
        RAISE_APPLICATION_ERROR(-20000,
            'V012_51: los arreglos v_dnis y v_siglas no tienen el mismo tamaño — revisar el script.');
    END IF;

    FOR i IN 1 .. v_dnis.COUNT LOOP
        BEGIN
            SELECT p.ID INTO v_persona_id
              FROM GESTIONRRHH.INDECI_PERSONA p
             WHERE p.DNI = v_dnis(i);

            SELECT e.ID INTO v_empleado_id
              FROM GESTIONRRHH.INDECI_EMPLEADO e
             WHERE e.PERSONA_ID = v_persona_id;

            SELECT d.ID INTO v_dependencia_id
              FROM GESTIONRRHH.INDECI_DEPENDENCIA d
             WHERE UPPER(TRIM(d.SIGLA)) = UPPER(TRIM(v_siglas(i)));

            UPDATE GESTIONRRHH.INDECI_EMPLEADO_PUESTO_HIST h
               SET h.DEPENDENCIA_ID = v_dependencia_id
             WHERE h.EMPLEADO_ID = v_empleado_id
               AND h.ACTIVO = 1
               AND h.DEPENDENCIA_ID IS NULL;

            v_actualizados := SQL%ROWCOUNT;
            IF v_actualizados > 0 THEN
                v_ok := v_ok + 1;
            ELSE
                v_sin_cambio := v_sin_cambio + 1;
            END IF;
        EXCEPTION
            WHEN NO_DATA_FOUND THEN
                -- Puede ser DNI inexistente en INDECI_PERSONA/EMPLEADO, o sigla
                -- inexistente en INDECI_DEPENDENCIA (no debería pasar tras
                -- V012_50, pero no se asume).
                v_sin_dni := v_sin_dni + 1;
                DBMS_OUTPUT.PUT_LINE('Omitido (DNI o sigla no encontrado): '
                        || v_dnis(i) || ' / ' || v_siglas(i));
        END;
    END LOOP;

    COMMIT;

    DBMS_OUTPUT.PUT_LINE('V012_51 -> actualizados: ' || v_ok
            || ' | ya tenían Dependencia (sin cambio): ' || v_sin_cambio
            || ' | omitidos (DNI/sigla no encontrado): ' || v_sin_dni);
END;
