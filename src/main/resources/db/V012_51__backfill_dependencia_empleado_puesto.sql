--     INDECI_DEPENDENCIA, o el empleado no tiene puesto activo con
--     DEPENDENCIA_ID nulo, la fila se omite y se loggea (no falla el script).
--   - NO toca el import de Vinculación (fix aparte, pendiente) — este script
