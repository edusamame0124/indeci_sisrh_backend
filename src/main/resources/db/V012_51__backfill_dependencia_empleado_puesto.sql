-- Origen del dato: docs/PLANTILLA_IMPORT_VINCULACION_oficial.xlsx (col BJ,
-- "Oficina / dependencia", texto libre) — la MISMA fuente que el import de
-- Vinculación usó para crear INDECI_OFICINA, pero que nunca se mapeó a
-- Dependencia (VinculacionUpsertService.upsertPuesto no setea dependenciaId).
