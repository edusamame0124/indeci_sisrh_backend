--     filas distintas del mismo Excel para la misma región) -> se fusionan
--     en una sola Dependencia por región.
--
-- Alcance y seguridad:
--   - Solo actualiza EMPLEADO_PUESTO_HIST con ACTIVO=1 Y DEPENDENCIA_ID IS
--     NULL (idempotente — no pisa nada que ya tenga valor, seguro de
--     re-correr).
